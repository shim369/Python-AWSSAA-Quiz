"""使い方: アプリの画面と操作の説明。数値は実装の定数から表示し、説明と動作がずれないようにする。"""

import streamlit as st

from python_awssaa_quiz.exam_bank import MOCK_EXAM_SIZE, PASSING_SCORE, SECONDS_PER_QUESTION
from python_awssaa_quiz.exam_guide import GUIDE_URL, TASKS, Domain
from python_awssaa_quiz.ui import setup_page

setup_page()
st.title("使い方")
st.caption("AWS 認定ソリューションアーキテクト – アソシエイト(SAA-C03)の学習用クイズアプリです。")

mock_minutes = MOCK_EXAM_SIZE * SECONDS_PER_QUESTION // 60

tab_start, tab_keyword, tab_exam, tab_dashboard, tab_add = st.tabs(
    ["はじめに", "キーワードクイズ", "本番形式", "ダッシュボード", "問題を増やす"]
)

# ---------------------------------------------------------------- はじめに
with tab_start:
    st.markdown(
        """
このアプリには、2種類の問題があります。

| | キーワードクイズ | 本番形式 |
|---|---|---|
| 目的 | サービスや用語を覚える | 本番と同じ形式のシナリオ問題に慣れる |
| 問題 | キーワード集から自動で作る4択 | 試験ガイドに沿って作ったシナリオ問題(4択・複数選択) |
| 始め方 | トップ画面で条件を選ぶ | サイドバーの「本番形式」 |
"""
    )
    st.subheader("おすすめの学習の流れ")
    st.markdown(
        """
1. **キーワードクイズ**でサービスや用語を覚える(まずは「概要 → キーワード」から)
2. **本番形式の練習**で、分野やタスクごとにシナリオ問題を解き、選択肢ごとの理由を読む
3. 本番形式で間違えた問題の関連キーワードは、キーワードクイズの「弱点優先」で出やすくなるので、そこで復習する
4. ある程度解けるようになったら**模擬試験**を受け、ダッシュボードでスコアの推移と苦手なタスクを確認する
"""
    )
    st.subheader("画面の移動")
    st.markdown("左のサイドバーから各画面に移動できます。解いている途中で別の画面に移っても、続きから再開できます。")
    c1, c2, c3 = st.columns(3)
    c1.page_link("app.py", label="キーワードクイズを始める", icon="🔤")
    c2.page_link("pages/4_本番形式.py", label="本番形式を始める", icon="📝")
    c3.page_link("pages/3_ダッシュボード.py", label="ダッシュボード", icon="📊")

# ---------------------------------------------------------------- キーワードクイズ
with tab_keyword:
    st.markdown(
        """
トップ画面で条件を選び、「クイズを始める」を押します。

| 設定 | 内容 |
|---|---|
| 分野 | 絞り込む分野(未選択ならすべて) |
| 重要度 | ★★★ / ★★ / ★ |
| 出題形式 | 下の3つから選ぶ。複数選ぶと、問題ごとにランダムで形式が決まる |
| 問題数 | 10問 / 20問 / 50問 / 全問 |
| 出題モード | ランダム / 弱点優先 / 間違えた問題だけ復習 |
| 詳細設定 | 乱数シード(同じシードなら同じ問題が出る) |
"""
    )
    st.subheader("出題形式")
    st.markdown(
        """
- **概要 → キーワード**:概要文から正しいキーワードを選ぶ(概要の中のキーワード名は「〇〇」で伏せてある)
- **キーワード → 概要**:キーワードから正しい概要を選ぶ
- **シナリオ → キーワード**:「試験での頻出ポイント」から、最適なサービス・機能を選ぶ
"""
    )
    st.subheader("出題モード")
    st.markdown(
        """
- **ランダム**:条件に合う問題からランダムに出題
- **弱点優先**:次のような問題ほど出やすくなる
    - 直近3回の回答で間違えた
    - 理解度が △(Excelの「理解度」列、または回答履歴からの判定)
    - 重要度が ★★★
    - まだ回答していない
    - 本番形式で、そのキーワードに関連する問題を間違えた
- **間違えた問題だけ復習**:直近3回の回答に不正解がある問題だけを出題
"""
    )
    st.subheader("回答と結果")
    st.markdown(
        """
- 選択肢を押すとすぐに正誤が表示され、そのキーワードの「概要」と「試験での頻出ポイント」を確認できます
- 結果画面では、正答率・分野別の正答率・間違えた問題の一覧を表示します。「間違えた問題をもう一度」で、間違えた問題だけをすぐ解き直せます
"""
    )

# ---------------------------------------------------------------- 本番形式
with tab_exam:
    st.markdown(
        f"""
本番の SAA-C03 と同じ形式のシナリオ問題です。

- **単一選択**:4つの選択肢から正解を1つ選ぶ
- **複数選択**:5つ以上の選択肢から、指定された数(「(2つ選択)」と表示)をチェックボックスで選ぶ

問題は [試験ガイド]({GUIDE_URL}) の{len(Domain)}分野・{len(TASKS)}タスクに分類しています。
選択肢の並びは出題のたびに変わります。設定画面の「収録されている問題」を開くと、タスクごとの問題数を確認できます。
"""
    )
    st.subheader("練習モード(1問ずつ答え合わせ)")
    st.markdown(
        """
1. 分野・タスクで絞り込み(未選択ならすべて)、問題数と問題の選び方を選んで「開始する」
    - **ランダム** / **弱点優先**(直近の不正解が多い・未回答の問題を優先)/ **間違えた問題だけ**
2. 選択肢を選んで「回答する」(複数選択の問題は、指定の数だけ選ぶと押せるようになる)
3. 正誤のあと、選択肢ごとの正解・不正解の理由、解説、関連キーワードを確認する
4. 「次の問題へ」で進む。途中で「ここで終了して結果を見る」も押せる
"""
    )
    st.subheader("模擬試験(最後にまとめて採点)")
    weights = " / ".join(f"{d.weight:.0%}" for d in Domain)
    st.markdown(
        f"""
1. 問題数({MOCK_EXAM_SIZE}問=本番と同じ / 30問 / 10問)とタイマーのON/OFFを選んで「開始する」
    - 全分野から、試験ガイドの出題比率({weights})に沿って選び、分野を混ぜて出題します
    - 収録されている問題が足りないときは、ある分だけ出題します
2. 回答しても答え合わせは出ません。「← 前へ」「次へ →」や「問題一覧」の番号で自由に移動し、回答を変えられます
3. 「試験を終了して採点する」で採点します。未回答の問題は不正解になります

**タイマー**

- **ON**:1問あたり{SECONDS_PER_QUESTION // 60}分({MOCK_EXAM_SIZE}問で{mock_minutes}分)。残り時間が表示され、時間切れになると自動的に採点します
- **OFF**:時間制限なし。経過時間だけを表示します
"""
    )
    st.subheader("結果画面")
    st.markdown(
        f"""
- 模擬試験はスコア(1000点満点の目安)と、合格ライン({PASSING_SCORE}点)との比較を表示します
- 分野別・タスク別の正答率と、問題ごとの解説を確認できます(「間違えた問題だけ表示」で絞り込める)
- 「間違えた問題を練習で解き直す」で、間違えた問題だけの練習をすぐ始められます
"""
    )
    st.info(
        "スコアは正答率を1000点に換算した目安です。本番は採点対象50問+採点対象外15問で、"
        "難易度を反映したスケールスコア(100〜1000点)で判定されます。",
        icon="ℹ️",
    )

# ---------------------------------------------------------------- ダッシュボード
with tab_dashboard:
    st.markdown(
        f"""
**キーワードクイズ**

- 学習済みキーワード数、総回答数、全体の正答率
- 分野別の正答率、日別の回答数と正答率

**本番形式**

- 模擬試験のスコア推移(点線は合格ライン {PASSING_SCORE}点)、受験回数、最新・最高スコア
- 分野別の正答率
- タスク別の正答率と収録問題数(収録の少ないタスクは、問題を増やす目安になる)

**Excelへの書き戻し**

「理解度を判定してExcelに書き戻す」ボタンで、キーワードクイズの回答履歴から理解度を判定し、
キーワード集の「理解度」列に書き込みます。

- 直近3回すべて正解なら **◎ 説明できる**、直近3回に1回でも正解があれば **○ なんとなく**、それ以外は **△ 要復習**
- まだ回答していないキーワードは変更しません
- 元のファイルは上書きせず、`_updated_YYYYMMDD.xlsx` を付けた別名で保存します(画面からダウンロードもできます)
"""
    )

# ---------------------------------------------------------------- 問題を増やす
with tab_add:
    st.markdown(
        """
本番形式の問題は、リポジトリの `data/exam_questions/` にあるYAMLファイルに保存されています。
増やし方は3通りあります(詳しい手順は README の「問題を増やす・更新する」)。

| 方法 | 向いている場面 |
|---|---|
| **Claude Code に頼む**(おすすめ) | 対話しながら少しずつ増やす。AWS公式ドキュメントでの事実確認つき |
| **YAMLを手で書く** | 自分で作った問題を足す |
| **Claude API のスクリプト** | まとめて大量に作る(API利用料がかかる) |

**Claude Code に頼む場合**

リポジトリのフォルダで Claude Code を起動し、「本番形式の問題を増やして」「タスク3.5の問題を4問作って」のように頼みます。
Claude が下書き・事実確認・形式の確認をしたうえで内容を見せるので、確認して了承した問題だけが追加されます。

追加した問題は、アプリを開いたままでもページを再読み込みすれば反映されます。
"""
    )
    st.warning(
        "AWS認定の試験問題は秘密保持契約(NDA)の対象です。"
        "「過去問」として出回っている問題集(ブレインダンプ)は認定プログラムの規約違反になるため、追加しないでください。"
        "本番に近い練習には、AWS公式のサンプル問題や AWS Skill Builder の公式練習問題集もおすすめです。",
        icon="⚠️",
    )
